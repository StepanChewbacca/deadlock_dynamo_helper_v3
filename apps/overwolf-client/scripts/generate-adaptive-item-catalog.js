const fs = require('node:fs');
const path = require('node:path');

const sourcePath = path.resolve(
  __dirname,
  '../../api/src/deadlock-live/reference-data.seed.ts',
);
const outputPath = path.resolve(
  __dirname,
  '../src/generated/adaptive-item-catalog.ts',
);

const source = fs.readFileSync(sourcePath, 'utf8');
const match = source.match(
  /export const ITEM_REFERENCE_SEED = (\[[\s\S]*?\]) as const;/,
);

if (!match) {
  throw new Error(`Unable to read ITEM_REFERENCE_SEED from ${sourcePath}`);
}

const items = JSON.parse(match[1]);
const entries = items
  .sort((left, right) => left.itemId - right.itemId)
  .map((item) => {
    const value = {
      id: item.itemId,
      name: toDisplayName(item.name),
      slot: item.item_slot_type,
      cost: item.cost,
      tier: item.item_tier,
    };
    return `  ${item.itemId}: ${JSON.stringify(value)},`;
  })
  .join('\n');

const output = `// Generated by scripts/generate-adaptive-item-catalog.js from the canonical item seed.\n` +
  `// Keep this file committed so the Overwolf UI has no runtime API dependency for labels.\n` +
  `export type AdaptiveItemSlot = 'weapon' | 'vitality' | 'spirit' | 'unknown';\n\n` +
  `export interface AdaptiveItemCatalogEntry {\n` +
  `  readonly id: number;\n` +
  `  readonly name: string;\n` +
  `  readonly slot: AdaptiveItemSlot;\n` +
  `  readonly cost: number;\n` +
  `  readonly tier: number;\n` +
  `}\n\n` +
  `export const ADAPTIVE_ITEM_CATALOG: Readonly<Record<number, AdaptiveItemCatalogEntry>> = {\n` +
  `${entries}\n` +
  `};\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    throw new Error('Adaptive item catalog is stale. Run: yarn generate:item-catalog');
  }
  console.log(`Verified ${items.length} committed adaptive item labels.`);
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated ${items.length} adaptive item labels at ${outputPath}`);
}

function toDisplayName(value) {
  if (!value.includes('_')) {
    return value;
  }

  const abbreviations = { aoe: 'AOE', t3: 'T3' };
  return value
    .replace(/^upgrade_/, '')
    .split('_')
    .filter(Boolean)
    .map((word) => abbreviations[word] || `${word.charAt(0).toUpperCase()}${word.slice(1)}`)
    .join(' ');
}
