const fs = require('node:fs');
const path = require('node:path');

const sourcePath = path.resolve(
  __dirname,
  '../../api/src/deadlock-live/reference-data.seed.ts',
);
const outputPath = path.resolve(
  __dirname,
  '../src/generated/adaptive-hero-catalog.ts',
);

const source = fs.readFileSync(sourcePath, 'utf8');
const match = source.match(
  /export const HERO_REFERENCE_SEED = (\[[\s\S]*?\]) as const;/,
);

if (!match) {
  throw new Error(`Unable to read HERO_REFERENCE_SEED from ${sourcePath}`);
}

const heroes = JSON.parse(match[1]);
const entries = heroes
  .map((hero) => ({ heroId: Number(hero.hero_id), name: String(hero.name).trim() }))
  .filter((hero) => Number.isSafeInteger(hero.heroId) && hero.heroId > 0 && hero.name.length > 0)
  .sort((left, right) => left.heroId - right.heroId)
  .map((hero) => {
    const value = {
      heroId: hero.heroId,
      name: hero.name,
      normalizedName: normalizeHeroName(hero.name),
    };
    return `  ${hero.heroId}: ${JSON.stringify(value)},`;
  })
  .join('\n');

const output = `// Generated by scripts/generate-adaptive-hero-catalog.js from the canonical hero seed.\n` +
  `// Keep this file committed so the Overwolf UI has no runtime API dependency for hero labels.\n` +
  `export interface AdaptiveHeroCatalogEntry {\n` +
  `  readonly heroId: number;\n` +
  `  readonly name: string;\n` +
  `  readonly normalizedName: string;\n` +
  `}\n\n` +
  `export const ADAPTIVE_HERO_CATALOG: Readonly<Record<number, AdaptiveHeroCatalogEntry>> = {\n` +
  `${entries}\n` +
  `};\n\n` +
  `export function getAdaptiveHeroDisplayName(heroId: number): string | undefined {\n` +
  `  return ADAPTIVE_HERO_CATALOG[heroId]?.name;\n` +
  `}\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    throw new Error('Adaptive hero catalog is stale. Run: yarn generate:hero-catalog');
  }
  console.log(`Verified ${heroes.length} committed adaptive hero labels.`);
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated ${heroes.length} adaptive hero labels at ${outputPath}`);
}

function normalizeHeroName(value) {
  return value.trim().toLowerCase().replace(/\s+/g, ' ');
}
